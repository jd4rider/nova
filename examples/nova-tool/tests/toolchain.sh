#!/bin/sh
# Corpus checks for the phase-1 Nova toolchain.
#
# Everything here runs the Nova implementations (fmt, lexer, diag, boxes) over
# the repository's own sources, so the port is measured against real code.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
NOVA="${NOVA_BIN:-$ROOT/bootstrap/nova}"
TOOL="$HERE/../target/nova/nova-tool"
OUT="${TMPDIR:-/tmp}/nova-tool-check"

[ -x "$NOVA" ] || { echo "toolchain: missing $NOVA (build the Nova compiler first)" >&2; exit 1; }
(cd "$HERE/.." && "$NOVA" build >/dev/null)
[ -x "$TOOL" ] || { echo "toolchain: build failed" >&2; exit 1; }

passed=0
failed=0
rm -rf "$OUT"
mkdir -p "$OUT"

check() {
    label="$1"
    shift
    if "$@" >/dev/null 2>&1; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        echo "FAIL $label"
    fi
}

assert_contains() {
    label="$1"
    needle="$2"
    file="$3"
    if grep -q "$needle" "$file"; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        echo "FAIL $label"
    fi
}

# 1. Formatting is idempotent over every Nova source in the repo.
for file in "$ROOT"/examples/*/src/*.nova "$ROOT"/libraries/*/src/*.nova; do
    [ -f "$file" ] || continue
    NOVA_TOOL=fmt NOVA_TOOL_PATH="$file" NOVA_TOOL_OUT="$OUT/formatted.nova" "$TOOL" >/dev/null
    result=$(NOVA_TOOL=check NOVA_TOOL_PATH="$OUT/formatted.nova" "$TOOL")
    if [ "$result" = "FORMATTED $OUT/formatted.nova" ]; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        echo "FAIL idempotent $file"
    fi
done

# 2. The lexer tokenizes every source without crashing, and finds tokens.
for file in "$ROOT"/examples/*/src/*.nova "$ROOT"/libraries/*/src/*.nova; do
    [ -f "$file" ] || continue
    if NOVA_TOOL=lex NOVA_TOOL_PATH="$file" "$TOOL" | grep -q "tokens=[1-9]"; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        echo "FAIL lex $file"
    fi
done

# 3. Every manifest parses through Nova Boxes with a valid name.
for file in "$ROOT"/examples/*/nova.toml; do
    [ -f "$file" ] || continue
    NOVA_TOOL=box NOVA_TOOL_PATH="$file" "$TOOL" > "$OUT/box.txt"
    assert_contains "manifest $file" "ok=true" "$OUT/box.txt"
    assert_contains "manifest name $file" "name=." "$OUT/box.txt"
done

# 4. Lockfile generation is deterministic and names the box.
NOVA_TOOL=lock NOVA_TOOL_PATH="$ROOT/examples/nova-tool/nova.toml" "$TOOL" > "$OUT/lock1"
NOVA_TOOL=lock NOVA_TOOL_PATH="$ROOT/examples/nova-tool/nova.toml" "$TOOL" > "$OUT/lock2"
check "lock deterministic" cmp -s "$OUT/lock1" "$OUT/lock2"
assert_contains "lock header" "generated by nova-boxes" "$OUT/lock1"
assert_contains "lock package" "nova-tool" "$OUT/lock1"

# 5. Import extraction finds the engine's own imports, deduplicated.
NOVA_TOOL=imports NOVA_TOOL_PATH="$ROOT/libraries/nova-engine/src/scene.nova" "$TOOL" > "$OUT/imports"
assert_contains "imports physics" "physics.nova" "$OUT/imports"
check "imports deduplicated" test "$(grep -c 'physics.nova' "$OUT/imports")" -eq 1

# 6. Diagnostics render with a location and a caret.
NOVA_TOOL=diag NOVA_TOOL_PATH="$ROOT/examples/nova-tool/src/main.nova" "$TOOL" > "$OUT/diag"
assert_contains "diagnostic severity" "error\[E0001\]" "$OUT/diag"
assert_contains "diagnostic caret" "\^" "$OUT/diag"

# 7. `nova lsp` runs the Nova language server, not the Rust stage-0 one.
NOVA_TOOL_BIN="$TOOL" python3 - "$NOVA" > "$OUT/entry-lsp" <<'PY'
import json, subprocess, sys
nova = sys.argv[1]
message = {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"capabilities": {}}}
body = json.dumps(message)
data = ("Content-Length: %d\r\n\r\n%s" % (len(body), body)).encode()
proc = subprocess.run([nova, "lsp"], input=data, capture_output=True, timeout=120)
sys.stdout.write(proc.stdout.decode("utf-8", "replace"))
PY
assert_contains "nova lsp uses the Nova server" '"version":"0.2.0"' "$OUT/entry-lsp"

echo "passed $passed, failed $failed"
[ "$failed" -eq 0 ]
